#!/usr/bin/env python3
"""Writes finance/budget-12-months.md (Nov-2026..Oct-2027) from model_summary.json."""
import json
import os

FIN = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = json.load(open(os.path.join(FIN, "model_summary.json")))
M, P = S["monthly"], S["periods"]
N = 12
k = lambda v: f"{v/1000:,.0f}" if abs(v) >= 500 else ("-" if abs(v) < 0.5 else f"{v/1000:,.1f}")
lines = [
    ("R&D salaries + burden", "rd_pc"), ("ID / ME / CMF agency", "nre_id"), ("ODM engineering NRE", "nre_odm"),
    ("Prototype builds (EVT/DVT/PVT)", "nre_proto"), ("Certification", "nre_cert"), ("City Pack content", "nre_content"),
    ("Dev tools & ML compute", "nre_sw"), ("S&M salaries + burden", "sm_pc"), ("Kickstarter marketing", "ks_mkt"),
    ("Crowdfunding fees", "ks_fees"), ("Brand / PR / content", "brand"), ("Paid acquisition", "paid"),
    ("Ops & CS salaries", "ops_pc"), ("G&A salaries (founder)", "ga_pc"), ("G&A non-personnel", "ga_other"),
]
hdr = "| $000 | " + " | ".join(P[:N]) + " | **12-mo total** |\n|---|" + "---:|" * (N + 1) + "\n"
body = ""
for lab, key in lines:
    v = M[key][:N]
    body += f"| {lab} | " + " | ".join(k(x) for x in v) + f" | **{k(sum(v))}** |\n"
opex = [sum(M[key][i] for _, key in lines) for i in range(N)]
body += "| **Total operating spend** | " + " | ".join(f"**{k(x)}**" for x in opex) + f" | **{k(sum(opex))}** |\n"
for lab, key, sign in [("Capex: tooling", "capex", -1), ("Inventory: ODM deposits & balances", "purch", -1),
                       ("Revenue (shipments from Nov-27)", "revenue", 1), ("Pre-order cash in (KS + late pledges)", "pre_cash", 1),
                       ("Equity in (SAFE, Seed)", "equity", 1), ("Net burn (op + inv cash flow)", "burn", 1), ("**Ending cash**", "cash", 1)]:
    v = M[key][:N]
    tot = "" if key == "cash" else f"**{k(sum(v))}**"
    body += f"| {lab} | " + " | ".join(k(x) for x in v) + f" | {tot} |\n"
hc = " | ".join(f"{x:.0f}" for x in M["hc"][:N])
body += f"| Headcount (end of month) | {hc} | |\n"
pre_seed_spend = sum(M["burn"][i] for i in range(9))  # Nov-26..Jul-27 (before Seed)
op9 = sum(opex[:9])
min_cash = min(M["cash"][:N])
txt = f"""# 12-month budget: pre-seed through Seed (Nov 2026 to Oct 2027)

*Generated by `scripts/make_budget_md.py` from the live model (base scenario). All figures are estimates in US$ thousands. Re-run `python3 finance/scripts/run_all.py && python3 finance/scripts/make_budget_md.py` after changing inputs.*

## What the money buys
| Milestone (COMPANY.md) | Month | Budget lines that pay for it |
|---|---|---|
| Phone-app prototype + Rome City Pack | Q4 2026 | 3 founding engineers, Rome content ($8k/mo), dev tools |
| ODM selected (legal-ops/supply-chain-ops.md) | Jan 2027 | Hardware lead hire, ODM NRE kick-off ($30k Dec + Jan) |
| 50 EVT units + beta | Q1 2027 | EVT build $35k (Feb), ID/ME agency $90k (Nov-Mar) |
| Kickstarter (public goal $150k, internal target $750k-1M) | May 2027 (payout Jun) | KS marketing $215k Jan-Jun, community lead |
| Seed $6M closes | Aug 2027 | -- |
| DVT/PVT, certification, tooling, first MP | Jul-Oct 2027 | ODM NRE, $625k cert Pebble+Square (Aug-Oct) + Atlas $640k (Nov-Dec), $695k tooling |
| First units ship | Nov 2027 | 30% ODM deposits from Aug, 70% balances from Oct |

## Month by month ($000)
{hdr}{body}
## Reading the table
* **Pre-seed runway.** The $1.5M SAFE funds Nov-26 to Jul-27: operating spend before the Seed is about **${op9/1e6:,.2f}M**, funded by the SAFE plus the Kickstarter payout (net burn ${pre_seed_spend/1e6:,.2f}M after pledges). Cash bottoms at **${min_cash/1e3:,.0f}k in May-27**, the month the campaign runs, so the pre-seed is **sufficient but has no slack.** If Kickstarter slips one month, cut the Atlas/ID spend and push the Community hire. A $250k founder/angel top-up on the same SAFE would restore a 3-month buffer.
* **Kickstarter cash.** Pledges arrive net of fees in Jun-27 and sit as **deferred revenue** until shipment (Nov-27 to Mar-28). It is spent on DVT tooling and the first ODM deposits. It is a liability to backers, not profit.
* **The big cheques after Seed.** These are certification (~$1.27M for three SKUs, from hardware/bom NRE), tooling (~$0.7M) and the ODM deposits on the first 5k units (30/70 terms, legal-ops/supply-chain-ops.md).
* **Hiring.** 2 people in Nov-26 (founder + embedded engineer) grow to 14 by Dec-27 (see `Headcount` sheet). Salaries are CFO estimates with 25% burden. Legal-ops owns the final bands (offer-letter template only so far).
"""
open(os.path.join(FIN, "budget-12-months.md"), "w").write(txt)
print("written budget-12-months.md")
