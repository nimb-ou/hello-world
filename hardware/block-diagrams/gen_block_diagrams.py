#!/usr/bin/env python3
"""Generate SVG + PNG system block diagrams for LORE Pebble / Square / Atlas.
Run: python3 gen_block_diagrams.py   (needs cairosvg: pip install cairosvg)"""
import os
import cairosvg

HERE = os.path.dirname(os.path.abspath(__file__))
C = dict(ink="#14161A", bone="#F3EEE6", terra="#C4623A", brass="#B8935A", olive="#5E6B4E", fog="#9AA0A6", night="#0D1B2A")
GROUP = {"compute": "#14161A", "rf": "#0D1B2A", "sensor": "#5E6B4E", "power": "#B8935A", "ui": "#C4623A", "audio": "#7F6A45",
         "sec": "#4A4F57"}

W, H = 1400, 900


def box(x, y, w, h, title, sub, g):
    fill = GROUP[g]
    s = f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="8" fill="{fill}" stroke="none"/>'
    s += f'<text x="{x+w/2}" y="{y+20}" fill="{C["bone"]}" font-size="13" font-weight="bold" text-anchor="middle">{title}</text>'
    for i, line in enumerate(sub):
        s += f'<text x="{x+w/2}" y="{y+37+i*14}" fill="{C["bone"]}" font-size="10.5" text-anchor="middle" opacity="0.9">{line}</text>'
    return s


def line(x1, y1, x2, y2, label="", col="#14161A", dash=False):
    d = ' stroke-dasharray="5,4"' if dash else ""
    s = f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{col}" stroke-width="1.6"{d} marker-end="url(#a)"/>'
    if label:
        mx, my = (x1 + x2) / 2, (y1 + y2) / 2
        s += (f'<rect x="{mx-len(label)*3.1-3}" y="{my-9}" width="{len(label)*6.2+6}" height="14" fill="{C["bone"]}"/>'
              f'<text x="{mx}" y="{my+2}" font-size="10" text-anchor="middle" fill="{col}">{label}</text>')
    return s


def svg(title, subtitle, body):
    head = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" font-family="DejaVu Sans, Inter, sans-serif">'
            f'<defs><marker id="a" markerWidth="8" markerHeight="8" refX="7" refY="4" orient="auto"><path d="M0,0 L8,4 L0,8 z" fill="#14161A"/></marker></defs>'
            f'<rect width="{W}" height="{H}" fill="{C["bone"]}"/>'
            f'<text x="30" y="42" font-size="26" font-family="DejaVu Serif, Fraunces, serif" fill="{C["ink"]}">{title}</text>'
            f'<text x="30" y="66" font-size="13" fill="{C["olive"]}">{subtitle}</text>')
    legend = "".join(f'<rect x="{30+i*150}" y="{H-36}" width="14" height="14" fill="{v}"/><text x="{50+i*150}" y="{H-24}" font-size="11">{k}</text>'
                     for i, (k, v) in enumerate(GROUP.items()))
    return head + body + legend + f'<text x="{W-30}" y="{H-24}" font-size="10" text-anchor="end" fill="{C["fog"]}">LORE Labs Hardware - generated by gen_block_diagrams.py</text></svg>'


def common(soc_title, soc_sub, ram, storage, x0=520, y0=300):
    b = box(x0, y0, 320, 170, soc_title, soc_sub, "compute")
    b += box(x0 + 20, y0 + 200, 130, 60, ram[0], ram[1:], "compute")
    b += box(x0 + 170, y0 + 200, 130, 60, storage[0], storage[1:], "compute")
    b += line(x0 + 85, y0 + 170, x0 + 85, y0 + 198, "LPDDR5")
    b += line(x0 + 235, y0 + 170, x0 + 235, y0 + 198, "UFS/eMMC")
    return b


def sensors_hub(x=60, y=300):
    b = box(x, y, 220, 70, "nRF54L15 always-on hub", ["Cortex-M33: fusion relay, SOS path", "owns haptics/LED/crown over I2C/SPI"], "compute")
    b += box(x, y + 100, 100, 62, "BHI360", ["6-axis IMU", "+fusion core"], "sensor")
    b += box(x + 120, y + 100, 100, 62, "BMM350", ["magnetometer"], "sensor")
    b += box(x, y + 182, 100, 52, "BMP390", ["barometer"], "sensor")
    b += line(x + 50, y + 100, x + 50, y + 72, "SPI")
    b += line(x + 170, y + 100, x + 170, y + 72, "I3C")
    b += line(x + 100, y + 200, x + 150, y + 72, "")
    return b


def pebble():
    b = common("MediaTek Genio 520 (MT8371)", ["2x A78 + 6x A55, 6 nm", "NPU 10 TOPS (1B INT4 LLM, ASR, TTS)", "Yocto / AOSP-lite", "TrustZone + OP-TEE"],
               ("LPDDR5 4 GB", "x32 6400"), ("eMMC 32 GB", "OS + 3 packs"))
    b += sensors_hub()
    b += line(282, 335, 518, 335, "UART + IRQ / wake")
    b += box(950, 110, 240, 80, "Wi-Fi 6 + BT 5.4 combo", ["MediaTek MT79xx", "A2DP src + LE Audio/Auracast", "BLE link to phone"], "rf")
    b += box(950, 230, 240, 64, "Quectel LC29HAA", ["GNSS L1+L5, 1 Hz / duty-cycled"], "rf")
    b += box(950, 330, 240, 64, "NXP SE050E", ["device identity / attestation"], "sec")
    b += box(950, 430, 240, 80, "Audio", ["2x IM73D122 PDM mics", "TAS2563 amp + 13x9 speaker", "(fallback)"], "audio")
    b += box(950, 550, 240, 64, "DRV2605L + LRA", ["haptics"], "ui")
    b += box(950, 650, 240, 64, "LP5024 + 8 RGB LEDs", ["LED ring (no screen)"], "ui")
    b += line(842, 330, 948, 150, "PCIe/SDIO + UART")
    b += line(842, 350, 948, 262, "UART + PPS")
    b += line(842, 370, 948, 362, "I2C")
    b += line(842, 400, 948, 470, "PDM + I2S")
    b += box(60, 640, 380, 150, "Power", ["Li-ion 650 mAh / 2.52 Wh (3.87 V)", "MAX77654 SIMO PMIC/charger (hub rails)",
                                          "Genio 520 companion PMIC (AP rails)", "MAX17262 fuel gauge", "USB-C (5 V sink) + 4-pin pogo"], "power")
    b += line(442, 700, 600, 562, "VSYS 3.4-4.45 V")
    b += box(60, 120, 380, 110, "Controls", ["Main button: press=talk, 2x=around me,", "long=SOS (hard-wired to hub GPIO)", "Volume rocker"], "ui")
    b += line(250, 232, 170, 298, "GPIO")
    return svg("LORE Pebble - system block diagram", "42 x 42 x 14 mm clip-on, no display, BLE+Wi-Fi, on-device ~1B model. Target battery 1.5 days.", b)


def square(atlas=False):
    soc = "MediaTek Genio 720 (MT8391)"
    ram = ("LPDDR5 8 GB" if atlas else "LPDDR5 6 GB", "x32 6400")
    sto = ("UFS 3.1 128 GB" if atlas else "UFS 2.2 64 GB", "")
    b = common(soc, ["2x A78 + 6x A55, 6 nm, Mali GPU", "NPU 10 TOPS (3-4B INT4 LLM" + (" + VLM)" if atlas else ")"),
                     "dual ISP" if atlas else "single display pipe", "AOSP (no GMS) / Yocto"], ram, sto)
    b += sensors_hub()
    b += line(282, 335, 518, 335, "UART + IRQ / wake")
    b += box(950, 90, 250, 80, "Quectel EG25-G", ["LTE Cat-4 global, 29x32 mm", "main + div ant., aperture tuner"], "rf")
    b += box(1220, 90, 150, 80, "Infineon OC1230", ["eUICC SGP.22", "WLCSP 1.8x1.6"], "sec")
    b += line(1200, 130, 1218, 130, "")
    b += box(950, 195, 250, 70, "Wi-Fi 6 + BT 5.4 combo", ["A2DP + LE Audio/Auracast"], "rf")
    b += box(950, 285, 250, 60, "Quectel LC29HAA", ["GNSS L1+L5"], "rf")
    b += box(950, 365, 250, 60, "AMOLED 1.6in 466x466", ["MIPI-DSI 1-lane, on-cell touch"], "ui")
    b += box(950, 445, 250, 70, "Audio", ["2x PDM mics, TAS2563 + 1511 spk", "codec in companion PMIC"], "audio")
    b += box(950, 535, 250, 60, "Crown + buttons + haptics", ["PAT9125 optical, DRV2605L+LRA"], "ui")
    b += box(950, 615, 250, 50, "NXP SE050E", ["identity / theft-lock"], "sec")
    b += line(842, 315, 948, 130, "USB2 HS + UART + PCM")
    b += line(842, 330, 948, 230, "PCIe/SDIO + UART")
    b += line(842, 345, 948, 315, "UART + PPS")
    b += line(842, 380, 948, 395, "MIPI-DSI + I2C")
    b += line(842, 410, 948, 480, "PDM + I2S/TDM")
    b += line(842, 440, 948, 640, "I2C")
    if atlas:
        b += box(950, 690, 250, 60, "Quectel BG95-S5", ["Rel-17 IoT-NTN (Skylo) SOS"], "rf")
        b += box(560, 600, 240, 56, "OV13B10 13 MP Glance cam", ["FF wide ~100 deg, CSI-2 4-lane"], "sensor")
        b += line(842, 460, 948, 720, "UART + PSM")
        b += line(680, 598, 680, 472, "CSI-2")
    bat = "1450 mAh / 5.63 Wh" if atlas else "1100 mAh / 4.27 Wh"
    b += box(60, 640, 400, 150, "Power", [f"Li-ion Si-C {bat} (3.88 V, 4.45 V max)", "BQ25620 buck charger (USB-C sink / pogo)",
                                          "Genio companion PMIC (AP rails)", "TPS63810 3.8 V LTE PA rail", "MAX17262 fuel gauge"], "power")
    b += line(462, 715, 540, 562, "VSYS")
    b += box(60, 120, 380, 110, "Controls", ["Crown: rotate=scroll/volume, press=talk", "Side button: 2x=around me", "SOS: long-press (hub GPIO, AP-independent)"], "ui")
    b += line(250, 232, 170, 298, "GPIO")
    if atlas:
        return svg("LORE Atlas - system block diagram",
                   "54 x 54 x 13.5 mm Ti + sapphire, LTE + eSIM + satellite SOS (NTN), Glance camera, on-device 3-4B + VLM. Target battery 3 days.", b)
    return svg("LORE Square - system block diagram",
               "54 x 54 x 12 mm anodised Al, 1.6in AMOLED, LTE Cat-4 + eSIM, BT 5.4 LE Audio, on-device 3B. Target battery 2 days.", b)


def main():
    for name, s in (("pebble", pebble()), ("square", square()), ("atlas", square(True))):
        p = os.path.join(HERE, f"{name}_block_diagram.svg")
        open(p, "w").write(s)
        cairosvg.svg2png(bytestring=s.encode(), write_to=p.replace(".svg", ".png"), output_width=W * 1.5)
        print("wrote", p)


if __name__ == "__main__":
    main()
