"""LORE mass budget (ESTIMATES). Housing volumes from params.json geometry; component masses from
hardware/system-architecture.md part choices + typical datasheet masses (marked est.).
Run: python3 industrial/scripts/mass_budget.py  -> prints markdown, writes industrial/mass-budget.md"""
import json, math, os
from math import gamma
D = os.path.dirname(os.path.abspath(__file__)); P = json.load(open(os.path.join(D, '..', 'params.json')))
rho = P['densities']

def se_area(w, h, n):  # superellipse area
    return w * h * gamma(1 + 1 / n) ** 2 / gamma(1 + 2 / n)
def se_perim(w, h, n, N=4000):
    pts = [(math.copysign(abs(math.cos(t)) ** (2 / n), math.cos(t)) * w / 2, math.copysign(abs(math.sin(t)) ** (2 / n), math.sin(t)) * h / 2) for t in [2 * math.pi * k / N for k in range(N)]]
    return sum(math.dist(pts[k], pts[(k + 1) % N]) for k in range(N))
def sq_area(w, r):  # rounded square (circular-corner approximation)
    return w * w - (4 - math.pi) * r * r
def sq_perim(w, r):
    return 4 * (w - 2 * r) + 2 * math.pi * r
CELL_WH_PER_G = 0.22  # est. small high-voltage pouch / stacked cells

def budget(sku):
    rows = []
    if sku == 'pebble':
        p = P['pebble']; A = se_area(42, 42, 2.6) / 100; L = se_perim(42, 42, 2.6) / 10  # cm2, cm
        shell = (2 * A + L * p['body_h'] / 10) * p['wall'] / 10  # cm3
        rows += [('Housing top + back, PC-GF10, 1.4 mm wall', shell * rho['PC_GF10'] * 0.92),
                 ('2K soft-touch PU paint (~40 um)', 0.4), ('Talk cap + PMMA light guide', 1.6),
                 ('Battery 650 mAh / 2.52 Wh', 2.52 / CELL_WH_PER_G),
                 ('Logic board + shields, Lite (D10): BT audio SoC, nRF54L15, 64 MB NOR, LC29HAA GNSS, 36x36 8L HDI', 3.6), ('Speaker 13x9 + acoustic seal', 1.3),
                 ('LORE Mount: 316L insert + N52 ring magnet', 1.9 + 1.5), ('4-pin pogo receiver, LRA, 2 mics, flexes, PSA, screws', 2.4)]
    else:
        s = dict(P['square']); s.update(P['atlas'] if sku == 'atlas' else {})
        T = s['thickness_total']; A = sq_area(54, 13) / 100; L = sq_perim(54, 13) / 10
        metal = rho['Ti_6Al4V'] if sku == 'atlas' else rho['Al_6013']
        frame = (L * (T - 0.8) / 10 * 0.12 + A * 0.12 * 0.35)  # 1.2 mm walls + partial floor ledge
        glass_a = sq_area(47, 10) / 100
        rows += [(('Unibody, Ti-6Al-4V' if sku == 'atlas' else 'Unibody, 6013-T6 Al') + ', 1.2 mm wall + ledges', frame * metal),
                 (('Cover, sapphire ' if sku == 'atlas' else 'Cover, Victus 2 ') + str(s['glass_t']) + ' mm', glass_a * s['glass_t'] / 10 * (rho['sapphire'] if sku == 'atlas' else rho['glass_victus2'])),
                 (('Back, zirconia 0.9 mm' if sku == 'atlas' else 'Back, AG glass 0.7 mm'), sq_area(45.6, 9) / 100 * (0.09 if sku == 'atlas' else 0.07) * (rho['zirconia'] if sku == 'atlas' else rho['glass_victus2'])),
                 ('AMOLED module 1.6" + on-cell touch', 2.6), ('Mid-frame SUS 0.2 stamped (display support, ground)', 2.2),
                 ('Thermal: Cu 50 um + 2x graphite + TIM + VC-lite 0.3' + (' + Ti-compatible VC 0.4 + Cu spreader' if sku == 'atlas' else ''), 3.0 if sku == 'atlas' else 1.4),
                 ('Battery ' + ('1450 mAh / 5.63 Wh' if sku == 'atlas' else '1100 mAh / 4.27 Wh'), (5.63 if sku == 'atlas' else 4.27) / CELL_WH_PER_G),
                 (('Logic boards, sandwich 2x46x46 + 1.6 interposer (Genio 720, 8 GB, 128 GB UFS, LTE, BG95-S5 NTN)' if sku == 'atlas' else 'Logic board 48x48 10L ELIC + shields (Genio 720, 6 GB, 64 GB UFS, LTE Cat-1bis per D11)'), 7.5 if sku == 'atlas' else 5.6),
                 ('Speaker 15x11, LRA, mics, flexes', 3.2), ('Crown (encoder) + Talk + SOS keys', 1.6 if sku == 'atlas' else 1.1),
                 ('LORE Mount: 316L insert + N52 ring magnet + 4-pin pogo', 3.6), ('Antennas, USB-C receptacle, PSA, gaskets, screws', 2.3)]
        if sku == 'atlas': rows.append(('Glance camera OV13B10 module + trim', 1.1))
    return rows

out = ['# LORE mass budget (ESTIMATES, EVT-0)', '', 'Generated by `industrial/scripts/mass_budget.py` from `params.json`. Housing masses are computed from geometry; electronics masses are typical-datasheet estimates for the parts chosen in `hardware/`. Weigh EVT units to replace. Atlas is computed at the D12 thickness of ' + str(P['atlas']['thickness_total']) + ' mm (frame height ' + str(P['atlas']['frame_h']) + ' mm).', '']
for sku in ['pebble', 'square', 'atlas']:
    rows = budget(sku); tot = sum(m for _, m in rows)
    out += [f'## {P[sku]["name"]} — **{tot:.0f} g** (est., ±10 %)', '', '| Item | g |', '|---|---:|'] + [f'| {n} | {m:.1f} |' for n, m in rows] + [f'| **Total** | **{tot:.1f}** |', '']
    print(f'{sku}: {tot:.1f} g')
open(os.path.join(D, '..', 'mass-budget.md'), 'w').write('\n'.join(out))
json.dump({sku: {'total_g': round(sum(m for _, m in budget(sku)), 1), 'parts': [[n, round(m, 2)] for n, m in budget(sku)]} for sku in ['pebble', 'square', 'atlas']}, open(os.path.join(D, '..', 'mass-budget.json'), 'w'), indent=1)

# refresh the generated block in id-spec.md, if present
spec = os.path.join(D, '..', 'id-spec.md')
if os.path.exists(spec):
    t = open(spec).read(); a, b = '<!-- mass-budget:begin -->', '<!-- mass-budget:end -->'
    if a in t and b in t:
        blk = [a, '']
        for sku in ['pebble', 'square', 'atlas']:
            rows = budget(sku); tot = sum(m for _, m in rows)
            blk += [f'**{P[sku]["name"]}: {tot:.1f} g** (estimate, ±10 %)', '', '| Part | g | % |', '|---|---:|---:|'] + [f'| {n} | {m:.1f} | {100 * m / tot:.0f} |' for n, m in rows] + [f'| **Total** | **{tot:.1f}** | 100 |', '']
        blk += [b]
        t = t[:t.index(a)] + '\n'.join(blk) + t[t.index(b) + len(b):]
        open(spec, 'w').write(t); print('  refreshed id-spec.md mass tables')
