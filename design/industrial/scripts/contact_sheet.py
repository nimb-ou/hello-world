"""Contact sheet of every render in renders/ -> renders/contact-sheet.png.
Run: python3 design/industrial/scripts/contact_sheet.py"""
import os, math
from PIL import Image, ImageDraw, ImageFont
D = os.path.dirname(os.path.abspath(__file__)); R = os.path.join(os.path.dirname(D), 'renders')
ORDER = ['hero', 'lineup', 'colourways', 'finish', 'exploded', 'ortho', 'scale', 'in-hand', 'on-', 'acc-']
files = sorted([f for f in os.listdir(R) if f.endswith('.png') and f != 'contact-sheet.png'],
               key=lambda f: (next((i for i, p in enumerate(ORDER) if f.startswith(p)), 99), f))
COLS, TW, TH, PAD, CAP, HEAD = 4, 720, 480, 28, 44, 150
rows = math.ceil(len(files) / COLS)
W = COLS * TW + (COLS + 1) * PAD; H = HEAD + rows * (TH + CAP + PAD) + PAD + 40
sheet = Image.new('RGB', (W, H), (243, 238, 230)); d = ImageDraw.Draw(sheet)
def font(names, size):
    for n in names:
        for base in ('/usr/share/fonts/truetype/dejavu/', '/usr/share/fonts/truetype/liberation/'):
            try: return ImageFont.truetype(base + n, size)
            except OSError: pass
    return ImageFont.load_default()
F_T, F_S, F_C = font(['DejaVuSerif.ttf'], 56), font(['DejaVuSans.ttf'], 22), font(['DejaVuSansMono.ttf'], 20)
d.text((PAD, 36), 'LORE · industrial design renders', fill=(20, 22, 26), font=F_T)
d.text((PAD, 106), f'{len(files)} renders · design/industrial/renders/ · generated by scripts/contact_sheet.py', fill=(110, 112, 116), font=F_S)
for i, f in enumerate(files):
    r, c = divmod(i, COLS); x = PAD + c * (TW + PAD); y = HEAD + r * (TH + CAP + PAD)
    im = Image.open(os.path.join(R, f)).convert('RGB'); im.thumbnail((TW, TH), Image.LANCZOS)
    sheet.paste(im, (x + (TW - im.width) // 2, y + (TH - im.height) // 2))
    d.rectangle([x - 1, y - 1, x + TW, y + TH], outline=(214, 207, 196))
    d.text((x, y + TH + 10), f, fill=(60, 62, 66), font=F_C)
d.text((PAD, H - 50), 'All renders are design visualisations of EVT-0 parametric models (params.json); not photographs of hardware.', fill=(130, 130, 130), font=F_S)
sheet.save(os.path.join(R, 'contact-sheet.png'), optimize=True)
print(f'renders/contact-sheet.png  {len(files)} images  {W}x{H}')
